def rendered_marker_path(store):
    return store.views_dir() / ".rendered_fingerprint"


def marker_value(st: dict, g: dict, reg: dict, cfg: dict, *,
                 fingerprint: str | None = None) -> str:
    """R9 audit: the page embeds the live policy/tempo projection, but the
    staleness marker hashed only state/graph/registry - a config-only preset
    change therefore never re-rendered, and the browser showed the old tempo
    for as long as an ordinary card stayed open. The marker now carries every
    authoritative input the page displays: the state triple AND the config
    projection."""
    import hashlib
    fp = fingerprint or eutil.state_fingerprint(st, g, reg)
    pol = hashlib.sha256(json.dumps(
        econfig.describe_policy(cfg), ensure_ascii=False).encode("utf-8")).hexdigest()[:16]
    return f"{fp}:{pol}"


def render(store, g: dict, cfg: dict, st: dict, reg: dict, *,
           infra_memo: dict | None = None, fingerprint: str | None = None) -> None:
    data = _data(store, g, cfg, st, reg, infra_memo=infra_memo)
    payload = json.dumps(data, ensure_ascii=True).replace("</", "<\\/")
    name = str((cfg.get("project") or {}).get("name") or "evolution")
    html = _fill_template(_esc(name) + " - evolution dashboard", payload)
    eutil.write_text(store.views_dir() / "DASHBOARD.html", html)
    # Record which authoritative inputs this dashboard reflects, so a later
    # no-op `next` can detect that some OTHER command (a rejected submit, a
    # gate decision, hold/resume, a config edit) changed them without
    # rendering and heal the staleness instead of skipping the render
    # forever. Callers that already computed the state fingerprint pass it in.
    eutil.write_text(rendered_marker_path(store),
                     marker_value(st, g, reg, cfg, fingerprint=fingerprint))


def _fill_template(title: str, payload: str) -> str:
    """Expand each fixed marker once, without rescanning replacement text."""
    replacements = {
        "@@TITLE@@": title,
        "@@DATA@@": payload,
    }
    # Substitute against the template once: user text containing the other
    # marker must never be scanned as a second template expansion.
    return re.sub(r"@@(?:TITLE|DATA)@@", lambda match: replacements[match.group(0)], _TEMPLATE)


def _esc(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _finite(value):
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return None
    return float(value) if math.isfinite(float(value)) else None


def _text(value, limit: int = 600) -> str:
    """Bound user-authored display text without guessing whether it is secret."""
    return str(value or "").strip()[:limit]


def _copy_fields(raw, fields: tuple[str, ...]) -> dict:
    if not isinstance(raw, dict):
        return {}
    return {key: raw.get(key) for key in fields if raw.get(key) is not None}


def _contract_view(cfg: dict) -> dict:
    """Allowlisted, joinable D/T/C/G metadata used by every dashboard view."""
    ev = econfig.evaluation_contract(cfg)
    metrics: dict[str, dict] = {}
    for raw in cfg.get("metrics") or []:
        if not isinstance(raw, dict) or not str(raw.get("key") or ""):
            continue
        key = str(raw["key"])
        metrics[key] = {
            "key": key, "name": _text(raw.get("name"), 160),
            "direction": str(raw.get("direction") or "max"),
            "definition": _text(raw.get("definition")),
        }

    def keyed(rows, *, id_field="id", fields=()):
        out: dict[str, dict] = {}
        order: list[str] = []
        for raw in rows or []:
            if not isinstance(raw, dict) or not str(raw.get(id_field) or ""):
                continue
            ident = str(raw[id_field])
            row = {id_field: ident}
            for key in fields:
                value = raw.get(key)
                if value is not None:
                    row[key] = _text(value) if isinstance(value, str) else value
            out[ident] = row
            order.append(ident)
        return out, order

    datasets, dataset_order = keyed(ev.get("datasets"), fields=("name", "split", "protocol"))
    tasks, task_order = keyed(ev.get("tasks"), fields=("name", "description", "aggregation", "weight"))
    cells, cell_order = keyed(ev.get("cells"), fields=(
        "dataset", "task", "metric", "result_key", "role", "weight",
        "min_improvement", "noninferiority_margin", "required",
        "goal_threshold", "goal_threshold_source",
    ))
    groups, group_order = keyed(ev.get("task_groups"), fields=(
        "name", "tasks", "aggregation", "required",
    ))
    return {
        "model_scope": str(ev.get("model_scope") or "single_checkpoint"),
        "display_cell": str(ev.get("display_cell") or ""),
        "metrics": metrics,
        "datasets": datasets,
        "tasks": tasks,
        "cells": cells,
        "groups": groups,
        "order": {"metrics": list(metrics), "datasets": dataset_order, "tasks": task_order,
                  "cells": cell_order, "groups": group_order},
        "decision": _copy_fields(ev.get("decision"), (
            "min_target_groups_improved", "min_target_groups_goal_met",
            "guardrails_must_be_noninferior", "allow_specialist",
        )),
        "assumptions": [_text(x) for x in (ev.get("assumptions") or []) if _text(x)],
    }


def _result_view(raw) -> dict | None:
    value = econfig.result_value(raw)
    if value is None:
        return None
    if not isinstance(raw, dict):
        return {"value": value, "interval": None,
                "evidence": {"kind": "scalar", "uncertainty_supplied": False}}
    replication = raw.get("training_replication")
    if isinstance(replication, dict):
        runs = [{"seed": run.get("seed"), "value": _finite(run.get("value"))}
                for run in (replication.get("runs") or [])[:32] if isinstance(run, dict)]
        return {"value": value, "interval": None,
                "evidence": {"kind": "training_replication",
                             "aggregation": replication.get("aggregation"),
                             "run_count": len(replication.get("runs") or []), "runs": runs,
                             "truncated": len(replication.get("runs") or []) > len(runs)}}
    uncertainty = raw.get("uncertainty")
    if isinstance(uncertainty, dict):
        point, lower, upper = econfig.result_interval(raw)
        evidence = _copy_fields(uncertainty, (
            "method", "unit", "unit_count", "aggregation", "resamples", "level"))
        evidence.update({"kind": "fixed_eval_uncertainty", "uncertainty_supplied": True})
        return {"value": point,
                "interval": {"lower": lower, "upper": upper,
                             "level": uncertainty.get("level")},
                "evidence": evidence}
    return {"value": value, "interval": None,
            "evidence": {"kind": "structured_value", "uncertainty_supplied": False}}


def _assessment_view(raw) -> dict:
    """Project the frozen engine assessment; never re-decide science in JS."""
    if not isinstance(raw, dict):
        return {}
    out = _copy_fields(raw, (
        "verdict", "display_delta_pct", "claim_kind", "overall_contract_pass",
        "project_goal_attained", "effect_contract_status", "mechanism_contract_status",
        "scientific_promotion_status", "configured_min_target_groups_improved",
    ))
    scalar_fields = ("cell", "metric", "result_key", "reference_node", "new", "reference",
                     "delta", "lower", "upper", "status", "goal_threshold", "goal_lower",
                     "goal_upper", "goal_status")
    out["cells"] = {str(key): _copy_fields(value, scalar_fields)
                    for key, value in (raw.get("cells") or {}).items() if isinstance(value, dict)}
    task_fields = ("id", "cells", "wins", "losses", "uncertain", "improved", "lost",
                   "aggregation", "weight")
    out["tasks"] = {str(key): _copy_fields(value, task_fields)
                    for key, value in (raw.get("tasks") or {}).items() if isinstance(value, dict)}
    out["goal_tasks"] = {str(key): _copy_fields(value, (
        "id", "cells", "met", "not_met", "unknown", "goal_met", "weight"))
        for key, value in (raw.get("goal_tasks") or {}).items() if isinstance(value, dict)}
    out["groups"] = [_copy_fields(value, (
        "id", "tasks", "cells", "wins", "losses", "uncertain", "required", "improved", "lost"))
        for value in (raw.get("groups") or []) if isinstance(value, dict)]
    out["goal_groups"] = [_copy_fields(value, (
        "id", "tasks", "met", "not_met", "unknown", "goal_met"))
        for value in (raw.get("goal_groups") or []) if isinstance(value, dict)]
    for key in ("target_cells", "guardrail_cells", "target_wins", "target_losses",
                "guardrail_losses", "guardrail_uncertain", "required_target_losses",
                "required_target_uncertain", "required_group_losses",
                "required_group_uncertain", "breadth_losses", "required_goal_not_met",
                "absolute_guardrail_not_met", "absolute_guardrail_unknown", "goal_groups_met"):
        if isinstance(raw.get(key), list):
            out[key] = [str(x) for x in raw[key]]
    effect_raw = raw.get("effect_contract") or {}
    effect = _copy_fields(effect_raw, ("status", "comparator_id", "comparator_node", "reason"))
    if isinstance(effect_raw.get("evidence_gaps"), list):
        effect["evidence_gaps"] = [str(x) for x in effect_raw["evidence_gaps"]]
    effect["targets"] = {str(key): _copy_fields(value, (
        "status", "result_key", "direction", "candidate", "comparator", "lower", "upper",
        "minimum_worthwhile_delta", "expected_lower", "expected_upper",
        "forecast_calibration", "reason"))
        for key, value in (effect_raw.get("targets") or {}).items() if isinstance(value, dict)}
    effect["guardrails"] = {str(key): _copy_fields(value, (
        "status", "result_key", "lower", "upper", "noninferiority_margin", "reason"))
        for key, value in (effect_raw.get("guardrails") or {}).items() if isinstance(value, dict)}
    resources_raw = effect_raw.get("resources") or {}
    resources = _copy_fields(resources_raw, ("status", "regime", "reason"))
    if isinstance(resources_raw.get("comparator_forecast_missed"), list):
        resources["comparator_forecast_missed"] = [
            str(x) for x in resources_raw["comparator_forecast_missed"]]
    resources["axes"] = {str(key): _copy_fields(value, (
        "status", "policy", "relation", "candidate_lower", "candidate_upper", "candidate_cap",
        "comparator_lower", "comparator_upper", "comparator_plan", "comparator_forecast", "reason"))
        for key, value in (resources_raw.get("axes") or {}).items() if isinstance(value, dict)}
    effect["resources"] = resources
    if effect.get("status") or effect["targets"] or effect["guardrails"] \
            or resources.get("axes") or resources.get("status"):
        out["effect_contract"] = effect
    mechanism_raw = raw.get("mechanism_contract") \
        if isinstance(raw.get("mechanism_contract"), dict) else {}
    mechanism = {}
    if mechanism_raw:
        mechanism = _copy_fields(mechanism_raw, (
            "status", "field", "aggregation", "aggregate", "comparison", "threshold",
            "lower", "upper", "reason"))
        raw_mechanism_values = mechanism_raw.get("values") \
            if isinstance(mechanism_raw.get("values"), list) else []
        mechanism_values = [value for raw_value in raw_mechanism_values
                            if (value := _finite(raw_value)) is not None]
        mechanism["observation_count"] = len(mechanism_values)
        mechanism["values"] = mechanism_values[:32]
        mechanism["truncated"] = len(mechanism_values) > 32
    for row in ([effect, resources, mechanism] + list(effect["targets"].values()) +
                list(effect["guardrails"].values()) + list(resources["axes"].values())):
        if row.get("reason") is not None:
            row["reason"] = _text(row.get("reason"), 480)
    if mechanism:
        out["mechanism_contract"] = mechanism
    return out


def _focus_view(cfg: dict, st: dict) -> dict:
    """Expose configured user bets and actual lane service without re-scheduling."""
    definitions = [row for row in ((cfg.get("project") or {}).get("focus_directions") or [])
                   if isinstance(row, dict) and str(row.get("id") or "")]
    # Same denominator as the validator's PORTFOLIO_FOCUS_SHARE arithmetic:
    # candidate lanes only. Counting instrumental lanes diluted the displayed
    # share, so a portfolio sitting exactly at the enforced cap rendered as
    # comfortably under it - the chip the user watches must agree with what
    # the engine will accept.
    lanes = [row for row in (st.get("lanes") or []) if isinstance(row, dict)
             and econfig.lane_purpose(row) not in econfig.INSTRUMENTAL_PURPOSES
             # (final audit C1) mirror candidate_lanes_for_mix exactly: a scout
             # neither dilutes the share nor discharges a starved direction.
             and econfig.lane_purpose(row) not in econfig.EXPLORATORY_PURPOSES]
    current_round = str(st.get("current_round") or "")
    current_lanes = [row for row in lanes if str(row.get("round") or "") == current_round]

    def served(rows: list[dict], focus_id: str) -> int:
        return sum(1 for row in rows if str(row.get("focus") or "") == focus_id)

    directions = []
    for raw in definitions:
        focus_id = str(raw.get("id"))
        directions.append({
            "id": focus_id,
            "text": _text(raw.get("text"), 600),
            "current_lanes": served(current_lanes, focus_id),
            "cumulative_lanes": served(lanes, focus_id),
        })
    current_focus = sum(1 for row in current_lanes if str(row.get("focus") or ""))
    current_total = len(current_lanes)
    cap = _finite((cfg.get("policy") or {}).get("focus_share_max"))
    return {
        "configured": bool(directions), "share_cap": cap,
        "current_round": current_round or None,
        "current": {"focus_lanes": current_focus, "all_lanes": current_total,
                    "share": (current_focus / current_total) if current_total else 0.0},
        "directions": directions,
    }


def _resource_view(cfg: dict, st: dict) -> dict:
    charged: dict[str, float] = {}
    totals_by_kind: dict[str, dict[str, float]] = {}
    totals_by_node: dict[str, dict[str, float]] = {}
    ledger = st.get("resource_ledger") or []
    for entry in ledger:
        usage = {str(unit): float(value) for unit, value in (entry.get("usage") or {}).items()
                 if _finite(value) is not None and float(value) >= 0}
        kind, node = str(entry.get("kind") or "other"), str(entry.get("node") or "-")
        for unit, value in usage.items():
            charged[unit] = charged.get(unit, 0.0) + value
            totals_by_kind.setdefault(kind, {})[unit] = totals_by_kind.setdefault(kind, {}).get(unit, 0.0) + value
            totals_by_node.setdefault(node, {})[unit] = totals_by_node.setdefault(node, {}).get(unit, 0.0) + value
    holders = ([t for t in st.get("tasks", []) if t.get("status") == "open"] +
               [r for r in st.get("runs", []) if erun.holds_reservation(r)])
    reserved: dict[str, float] = {}
    reservations: list[dict] = []
    for holder in holders:
        usage = {str(unit): float(value) for unit, value in (holder.get("resource_reservation") or {}).items()
                 if _finite(value) is not None and float(value) >= 0}
        if not usage:
            continue
        for unit, value in usage.items():
            reserved[unit] = reserved.get(unit, 0.0) + value
        is_run = "node" in holder and "kind" in holder
        reservations.append({
            "holder": "run" if is_run else "task", "id": str(holder.get("id") or ""),
            "node": str(holder.get("node") or (holder.get("subject") or {}).get("node") or ""),
            "kind": str(holder.get("kind") or holder.get("type") or ""), "usage": usage,
        })
    base = econfig.resource_limits(cfg)
    overrides = {str(unit): float(value) for unit, value in (st.get("resource_overrides") or {}).items()
                 if _finite(value) is not None}
    units: dict[str, dict] = {}
    for unit in sorted(set(base) | set(overrides) | set(charged) | set(reserved)):
        base_limit = float(base.get(unit, 0.0))
        addition = float(overrides.get(unit, 0.0))
        effective = base_limit + addition
        used, held = charged.get(unit, 0.0), reserved.get(unit, 0.0)
        available = effective - used - held
        if unit not in base:
            status = "unconfigured"
        elif available < -1e-12:
            status = "exhausted"
        elif effective and available <= effective * .1:
            status = "pressure"
        else:
            status = "healthy"
        units[unit] = {"base_limit": base_limit, "approved_addition": addition,
                       "effective_limit": effective, "charged": used, "reserved": held,
                       "available": available, "status": status}
    statuses = {row["status"] for row in units.values()}
    health = ("exhausted" if "exhausted" in statuses else
              "pressure" if "pressure" in statuses else
              "unconfigured" if not units or "unconfigured" in statuses else "healthy")
    recent_limit = 24
    recent = [{"id": str(x.get("id") or ""), "node": str(x.get("node") or ""),
               "kind": str(x.get("kind") or ""), "run": x.get("run"), "task": x.get("task"),
               "usage": {str(k): float(v) for k, v in (x.get("usage") or {}).items()
                         if _finite(v) is not None},
               "basis": str(x.get("basis") or ""), "charged_at": x.get("charged_at")}
              for x in ledger[-recent_limit:]]
    return {"on_exhaustion": str((cfg.get("resource_contract") or {}).get("on_exhaustion") or "ask"),
            "health": health, "units": units, "reservations": reservations,
            "ledger": {"count": len(ledger), "totals_by_kind": totals_by_kind,
                       "totals_by_node": totals_by_node, "recent": recent,
                       "recent_limit": recent_limit, "truncated": len(ledger) > recent_limit}}


def _infrastructure_view(store, cfg: dict, st: dict, g: dict, running_stages: dict,
                         infra_memo: dict | None = None) -> dict:
    # The scheduler's frozen-contract assertion just validated the identical
    # facts/canary bytes in this same invocation; reuse its answer instead of
    # re-reading and re-hashing the whole evidence bundle for the dashboard.
    memo = infra_memo if isinstance(infra_memo, dict) else {}
    facts = memo["facts"] if "facts" in memo else einfra.load_facts(store, cfg)
    fact_errors = einfra.validate_facts(store, facts) if facts is not None else []
    slots_total = einfra.slots_from_facts(store, cfg, facts=facts)
    facts_slots = (((facts or {}).get("compute") or {}).get("max_concurrent_stage_jobs"))
    source = "infra_facts" if isinstance(facts_slots, int) and facts_slots >= 1 else "config"
    services = []
    for raw in (facts or {}).get("services") or []:
        if isinstance(raw, dict) and raw.get("name"):
            services.append({"name": _text(raw.get("name"), 100), "kind": _text(raw.get("kind"), 160)})
    if isinstance((facts or {}).get("llm"), dict):
        services.append({"name": "llm", "kind": _text(facts["llm"].get("kind"), 160)})
    datasets = [{"name": _text(raw.get("name"), 140), "role": _text(raw.get("role"), 180)}
                for raw in (((facts or {}).get("data") or {}).get("datasets") or [])
                if isinstance(raw, dict)]
    facts_view = {
        "present": facts is not None, "valid": facts is not None and not fact_errors,
        "validation_error_codes": sorted({str(x).split(":", 1)[0] for x in fact_errors}),
        "compute_kind": _text(((facts or {}).get("compute") or {}).get("kind"), 160),
        "data_kind": _text(((facts or {}).get("data") or {}).get("kind"), 160),
        "datasets": datasets, "dataset_count": len(datasets),
        "artifact_kind": _text(((facts or {}).get("artifact_store") or {}).get("kind"), 160),
        "evaluation_declared": isinstance((facts or {}).get("evaluation"), dict),
        "evaluation_result_key_count": len((((facts or {}).get("evaluation") or {}).get("result_keys") or [])),
        "services": services, "service_count": len(services),
    }

    record = st.get("infra_canary") if isinstance(st.get("infra_canary"), dict) else None
    active = record is not None
    if record is None:
        for task in reversed(st.get("tasks") or []):
            candidate = task.get("infra_canary_run")
            if task.get("type") == "infra_drill" and isinstance(candidate, dict):
                record = candidate
                break
    if record is not None and record is memo.get("canary_record"):
        validation_errors = list(memo.get("canary_errors") or [])
    else:
        validation_errors = (ecanary.record_errors_for_snapshot(
            store, record, cfg=cfg, st=st, require_passed=False,
            facts=facts if facts is not None else None) if record else [])
    receipt, _receipt_errors = ecanary.verified_receipt(store, record) if record else (None, [])
    validation_codes = {str(x).split(":", 1)[0] for x in validation_errors}
    stale_codes = {"CANARY_CONTRACT_MUTATED", "CANARY_FACTS_MUTATED"}
    hard_errors = [x for x in validation_errors if str(x).split(":", 1)[0] not in stale_codes]
    stale = False
    if record:
        approved_facts = str(st.get("bootstrap_infra_facts_digest") or "")
        current_facts = memo.get("facts_digest") or ecanary.facts_digest_of(facts)
        stale = (not approved_facts
                 or str(record.get("infra_facts_digest") or "") != approved_facts
                 or current_facts != approved_facts
                 or str(record.get("bootstrap_contract_digest") or "") !=
                 str(st.get("bootstrap_contract_digest") or "")
                 or (bool(st.get("bootstrap_contract_digest")) and
                     econfig.bootstrap_contract_digest(cfg) != str(st.get("bootstrap_contract_digest"))))
    stale = stale or bool(validation_codes & stale_codes)
    status = str((record or {}).get("status") or "not_run")
    if hard_errors:
        status = "invalid"
    elif stale:
        status = "stale"
    required = list((receipt or {}).get("required_surfaces") or
                    ecanary.required_surfaces(store, cfg, facts=facts))
    by_kind = {"base": 0, "dataset": 0, "evaluation_dataset": 0, "service": 0}
    for surface in required:
        if str(surface).startswith("evaluation-dataset:"):
            by_kind["evaluation_dataset"] += 1
        elif str(surface).startswith("dataset:"):
            by_kind["dataset"] += 1
        elif str(surface).startswith("service:"):
            by_kind["service"] += 1
        else:
            by_kind["base"] += 1
    ready = bool(active and status == "passed" and receipt and facts_view["valid"]
                 and not validation_errors)
    blocker_count = len([x for x in ((receipt or {}).get("blockers") or []) if isinstance(x, dict)])
    error_codes = sorted({str(x).split(":", 1)[0]
                          for x in ((receipt or {}).get("errors") or []) if str(x)})
    error_codes += list(validation_codes)
    canary = {
        "scope": "bootstrap_declared_external_surfaces",
        "status": status, "ready": ready, "active": active,
        "verified": bool(receipt is not None and not hard_errors),
        "stale": stale, "task": (record or {}).get("task"),
        "attempt": (record or {}).get("attempt"), "ran_at": (record or {}).get("ran_at"),
        "failure_attempt": (receipt or {}).get("failure_attempt"),
        "attempt_limit": (receipt or {}).get("attempt_limit"),
        "exhausted": bool((receipt or {}).get("exhausted")),
        "coverage": {"required": len(required), "passed": len(required) if ready else 0,
                     "by_kind": by_kind},
        "blocker_count": blocker_count,
        "error_codes": sorted(set(error_codes)),
    }
    return {"ready": ready, "facts": facts_view, "canary": canary,
            "slots": {"total": slots_total, "busy": len(running_stages),
                      "free": max(0, slots_total - len(running_stages)), "source": source}}


def _cell_records_with_provisional(g: dict, cfg: dict, st: dict | None) -> list[dict]:
    """v11.1 P6: the dashboard's record rows carry the winner's-curse label too."""
    rows = egraph.cell_records(g, cfg)
    idx = egraph.by_id(g)
    eligible = [n for n in g.get("nodes", []) if egraph.observation_eligible(n, cfg)]
    for row in rows:
        holder = idx.get(row["node"]) or {}
        row["provisional"] = egraph.provisional_record(
            holder, [n for n in eligible if n.get("id") != row["node"]], cfg,
            cell_id=row["cell"], st=st)
    return rows


